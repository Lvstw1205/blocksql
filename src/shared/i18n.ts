const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, ko }
let current: Lang = 'en'

export const setLang = (lang: Lang): void => {
  current = dictionaries[lang] ? lang : 'en'
}
export const getLang = (): Lang => current

/** Translate a message; {placeholders} are filled from vars. */
export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (m, k: string) =>
    k in vars ? (typeof vars[k] === 'number' ? vars[k].toLocaleString() : String(vars[k])) : m
  )
}
